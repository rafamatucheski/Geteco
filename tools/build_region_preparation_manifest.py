"""Generate exported resource lists without parsing GDScript during gameplay."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REFERENCES = re.compile(r'[\"\'](res://[^\"\'\n]+)[\"\']')
RESOURCE_EXTENSIONS = {'.tscn', '.scn', '.tres', '.res', '.glb', '.gltf', '.png', '.jpg', '.jpeg', '.webp', '.svg', '.wav', '.ogg', '.mp3', '.ttf', '.otf', '.gdshader'}

def build():
    roots = {
        'harbor': ['world/regions', 'world/urban_detail', 'world/harbor_route_detail', 'world/city_look', 'assets/regions/source/world/harbor'],
        'mountain': ['world/regions', 'world/mountain_detail', 'assets/regions/source/world/mountain_pass'],
        'desert': ['world/desert', 'world/mining'],
    }
    result = {}
    for region, folders in roots.items():
        paths = set()
        for folder in folders:
            for source in (ROOT / folder).rglob('*.gd'):
                for path in REFERENCES.findall(source.read_text(encoding='utf-8-sig')):
                    if Path(path).suffix in RESOURCE_EXTENSIONS and (ROOT / path.removeprefix('res://')).is_file():
                        paths.add(path)
        result[region] = sorted(paths)
    return result

if __name__ == '__main__':
    output = ROOT / 'runtime/RegionPreparationResources.gd'
    manifest = build()
    output.write_text('# Generated by tools/build_region_preparation_manifest.py\nextends RefCounted\nconst RESOURCES := ' + json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print({region: len(paths) for region, paths in manifest.items()})
